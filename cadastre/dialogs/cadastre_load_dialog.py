import os.path


from qgis.PyQt import uic
from qgis.PyQt.QtCore import Qt
from qgis.PyQt.QtWidgets import QDialog, QMessageBox
from qgis.utils import OverrideCursor

from cadastre.cadastre_loading import CadastreLoading, LoadingOptions
from cadastre.dialogs.database_widget import DatabaseWidget
from cadastre.dialogs.dialog_feedback import CadastreDialogFeedback, append_log
from cadastre.tools import plugin_path, set_window_title

LOAD_FORM_CLASS, _ = uic.loadUiType(str(plugin_path("forms", "cadastre_load_form.ui")))


class CadastreLoadDialog(QDialog, LOAD_FORM_CLASS):  # type: ignore[valid-type, misc]  # Class generated by uic at runtime
    """Load data from database."""

    def __init__(self, iface, cadastre_search_dialog, parent=None):
        super().__init__(parent)
        self.iface = iface
        self.setupUi(self)
        self.setWindowTitle(f"{self.windowTitle()} {set_window_title()}")
        self.mc = self.iface.mapCanvas()

        self.cadastre_search_dialog = cadastre_search_dialog

        self.ql = CadastreLoading(CadastreDialogFeedback(self.txtLog, self.pbProcess), self.mc)

        # Database, connection and schema
        self.database_widget = DatabaseWidget(self)
        self.databaseLayout.addWidget(self.database_widget)
        self.database_widget.logMessage.connect(lambda msg: append_log(self.txtLog, msg))

        # Get style list
        self.getStyleList()

        # Signals/Slot Connections
        self.btProcessLoading.clicked.connect(self.onProcessLoadingClicked)
        self.ql.cadastreLoadingFinished.connect(self.onLoadingEnd)

        self.btLoadSqlLayer.clicked.connect(self.onLoadSqlLayerClicked)

        self.rejected.connect(self.onClose)
        self.buttonBox.rejected.connect(self.onClose)

        self.database_widget.load_settings()

    def onClose(self):
        """
        Close dialog
        """
        self.database_widget.close_connection()
        self.close()

    def getStyleList(self):
        """
        Get the list of style directories
        inside the plugin dir
        and add combobox item
        """
        spath = str(plugin_path("styles"))
        dirs = os.listdir(spath)
        dirs = [a for a in dirs if os.path.isdir(os.path.join(spath, a))]
        dirs.sort()
        cb = self.liTheme
        cb.clear()
        for d in dirs:
            cb.addItem("%s" % d, d)

    def onProcessLoadingClicked(self):
        """
        Activate the loading of layers
        from database tables
        when user clicked on button
        """
        database = self.database_widget.database()
        if not database:
            return

        options = LoadingOptions(
            database=database,
            theme=self.liTheme.currentText(),
            commune_expression=self.communeFilter.text(),
            main_layers_only=self.cbMainLayersOnly.isChecked(),
        )
        with OverrideCursor(Qt.CursorShape.WaitCursor):
            self.ql.process_loading(options)

        if os.getenv("CI", "").lower() != "true":
            # We don't want QMessagebox in test
            QMessageBox.information(self, "Cadastre", "Les données ont bien été chargées dans QGIS")

    def onLoadSqlLayerClicked(self):
        """
        Loads a layer
        from given SQL
        when user clicked on button
        """
        database = self.database_widget.database()
        if database:
            self.ql.load_sql_layer(
                database,
                self.sqlText.toPlainText(),
                self.geometryColumn.text(),
                self.layerName.text(),
            )

    def onLoadingEnd(self):
        """
        Actions to trigger
        when all the layers
        have been loaded
        """
        self.cadastre_search_dialog.checkMajicContent()
        self.cadastre_search_dialog.clearComboboxes()
        self.cadastre_search_dialog.setupSearchCombobox("commune", None, "sql")
        self.cadastre_search_dialog.setupSearchCombobox("commune_proprietaire", None, "sql")
        # self.cadastre_search_dialog.setupSearchCombobox('section', None, 'sql')
