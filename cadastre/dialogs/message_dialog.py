from qgis.core import QgsProviderConnectionException
from qgis.PyQt import uic
from qgis.PyQt.QtCore import Qt
from qgis.gui import QgisInterface
from qgis.PyQt.QtWidgets import QDialog, QGroupBox, QLabel, QPushButton, QVBoxLayout, QWidget
from qgis.utils import OverrideCursor

from cadastre.dialogs.database_widget import DatabaseWidget
from cadastre.logger import Logger
from cadastre.tools import plugin_path, set_window_title
from cadastre.upgrade import run_sql, sql_statements

MESSAGE_FORM_CLASS, _ = uic.loadUiType(str(plugin_path("forms", "cadastre_message_form.ui")))


class CadastreMessageDialog(QDialog, MESSAGE_FORM_CLASS):  # type: ignore[valid-type, misc]  # Class generated by uic at runtime
    """Displays a message to the user, and runs the SQL commands of the update messages if any.

    When the messages of the given versions have SQL commands, a box lets the user choose the
    database of the cadastre data, which may not be the one of the current project, and run them.
    """

    def __init__(
        self,
        iface: QgisInterface,
        message: str,
        sql_versions: list[tuple[int, ...]] | None = None,
        parent: QWidget | None = None,
    ):
        """
        :param iface: The QGIS interface.
        :param message: The HTML of the message.
        :param sql_versions: The versions of the update messages whose SQL commands can be run, see upgrade.
        :param parent: The parent widget.
        """
        super().__init__(parent)
        self.iface = iface
        self.setupUi(self)
        self.setWindowTitle(f"{self.windowTitle()} {set_window_title()}")

        self.teMessage.setText(message)

        # SQL commands of the messages: the box to choose the database and run them
        self.sql_versions = [v for v in sql_versions or [] if sql_statements([v], True)]
        self.database_widget: DatabaseWidget | None = None
        if self.sql_versions:
            self.add_sql_box()
            self.resize(self.width(), 650)

        # Signals/Slot Connections
        self.rejected.connect(self.onReject)
        self.buttonBox.rejected.connect(self.onReject)
        self.buttonBox.accepted.connect(self.onAccept)

    def add_sql_box(self):
        """Add the box to choose a database and run the SQL commands, above the buttons."""
        box = QGroupBox("Exécuter les commandes SQL dans une base de données du cadastre", self)
        layout = QVBoxLayout(box)
        self.database_widget = DatabaseWidget(box)
        layout.addWidget(self.database_widget)
        self.btRunSql = QPushButton("Exécuter le SQL", box)
        layout.addWidget(self.btRunSql)
        self.lbSqlResult = QLabel(box)
        self.lbSqlResult.setWordWrap(True)
        self.lbSqlResult.setTextInteractionFlags(Qt.TextInteractionFlag.TextSelectableByMouse)
        layout.addWidget(self.lbSqlResult)
        # Above the button box, the last item of the layout of the form
        self.verticalLayout.insertWidget(self.verticalLayout.count() - 1, box)

        self.database_widget.logMessage.connect(self.lbSqlResult.setText)
        self.database_widget.databaseChanged.connect(lambda _db: self.lbSqlResult.clear())
        self.btRunSql.clicked.connect(self.run_sql)
        # The database used last time in the plugin, like the import and loading dialogs
        self.database_widget.load_settings()

    def run_sql(self):
        """Run the SQL commands in the chosen database, and display the result below the button."""
        database = self.database_widget.database() if self.database_widget else None
        if database is None or (database.is_postgis and not database.schema):
            self.lbSqlResult.setText("Choisir une connexion, et le schéma des données cadastrales pour PostgreSQL.")
            return

        self.lbSqlResult.setText("Exécution en cours, cela peut prendre quelques minutes…")
        self.repaint()
        try:
            with OverrideCursor(Qt.CursorShape.WaitCursor):
                count = run_sql(database, self.sql_versions)
        except (ValueError, QgsProviderConnectionException) as e:
            Logger.warning(f"Erreur lors de l'exécution du SQL de mise à jour : {e!s}")
            self.lbSqlResult.setText(f"Erreur : {e!s}")
            return
        self.lbSqlResult.setText(f"{count} commande(s) SQL exécutée(s) avec succès.")

    def onAccept(self):
        """
        Save options when pressing OK button
        """
        self.close_database()
        self.accept()

    def onReject(self):
        """
        Run some actions when
        the user closes the dialog
        """
        self.close_database()
        self.close()

    def close_database(self):
        """Close the connection of the database box, if any."""
        if self.database_widget:
            self.database_widget.close_connection()
