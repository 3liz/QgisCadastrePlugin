from qgis.PyQt import uic
from qgis.PyQt.QtWidgets import QDialog

from cadastre.tools import plugin_path, set_window_title

MESSAGE_FORM_CLASS, _ = uic.loadUiType(str(plugin_path("forms", "cadastre_message_form.ui")))


class CadastreMessageDialog(QDialog, MESSAGE_FORM_CLASS):  # type: ignore[valid-type, misc]  # Class generated by uic at runtime
    """Displays a message to the user."""

    def __init__(self, iface, message, parent=None):
        super().__init__(parent)
        self.iface = iface
        self.setupUi(self)
        self.setWindowTitle(f"{self.windowTitle()} {set_window_title()}")

        self.teMessage.setText(message)

        # Signals/Slot Connections
        self.rejected.connect(self.onReject)
        self.buttonBox.rejected.connect(self.onReject)
        self.buttonBox.accepted.connect(self.onAccept)

    def onAccept(self):
        """
        Save options when pressing OK button
        """
        self.accept()

    def onReject(self):
        """
        Run some actions when
        the user closes the dialog
        """
        self.close()
